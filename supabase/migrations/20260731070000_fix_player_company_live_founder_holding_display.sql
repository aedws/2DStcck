-- 회사 탭의 실제 창업주 보유량은 거래 직후 계좌 정밀 수량을 우선하고,
-- 서버 요약은 다른 장기주주의 확정 의결권에만 사용한다.
-- 코드 배포와 함께 문의를 처리 완료로 전환한다.

update public.bug_reports
set
  status = 'fixed',
  admin_note = '원인을 확인했습니다. 대량 매매 수량 자체는 정밀 수량으로 정상 보존됐지만, 회사 탭이 과거 서버 요약을 최신 계좌보다 우선 표시해 갱신되지 않은 것처럼 보였습니다. 이제 내 실제 보유주식과 지분율은 거래 직후 계좌의 최신 정밀 수량으로 즉시 갱신하고, 다음 주총 예상 의결권은 최신 창업주 수량에 서버가 확인한 다른 90거래일 장기주주의 수량만 합쳐 계산합니다.',
  updated_at = now()
where id = 'c58f3899-031f-4d1d-a572-436b72c18cb4'
  and status in ('open', 'investigating');
